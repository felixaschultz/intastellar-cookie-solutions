/**
 * Precomputes notRequired RegExp source strings from dev/gdpr.dev.js allScripts.
 * Run: node scripts/build-not-required-patterns.mjs
 */
import fs from "fs";
import path from "path";
import vm from "vm";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const srcPath = path.join(root, "dev", "gdpr.dev.js");
const outPath = path.join(root, "dev", "uc-not-required-patterns.dev.js");

const gdprLines = fs.readFileSync(srcPath, "utf8").split("\n");
const arraySrc = gdprLines
    .slice(173, 314)
    .join("\n")
    .replace(/^let allScripts = window\.allScripts = /, "var allScripts = ");
const allScripts = vm.runInNewContext(arraySrc + "\nallScripts;", {}, { timeout: 5000 });
if (!Array.isArray(allScripts) || allScripts.length < 3) {
    throw new Error("Failed to parse allScripts from gdpr.dev.js lines 174–314");
}

function merge(first, second, third) {
    for (let j = 0; j < second.length; j++) {
        first.push(second[j]);
    }
    if (third !== undefined) {
        for (let j = 0; j < third.length; j++) {
            first.push(third[j]);
        }
    }
    return first;
}

const VARIANTS = {
    functional_only: () => merge(allScripts[1].scripts.slice(), allScripts[0].scripts),
    marketing_only: () => merge(allScripts[2].scripts.slice(), allScripts[0].scripts),
    stats_only: () => merge(allScripts[1].scripts.slice(), allScripts[2].scripts),
    functional_stats: () => allScripts[1].scripts.slice(),
    functional_marketing: () => allScripts[0].scripts.slice(),
    marketing_stats: () => allScripts[2].scripts.slice(),
    default: () => merge(allScripts[0].scripts.slice(), allScripts[1].scripts, allScripts[2].scripts),
    all_granted: () => ["^$"],
};

const sources = {};
for (const [key, build] of Object.entries(VARIANTS)) {
    sources[key] = build().join("|");
}

const body =
    "/* Generated by scripts/build-not-required-patterns.mjs — do not edit. */\n" +
    "window.__intaNotRequiredPatternSources = " +
    JSON.stringify(sources, null, 4) +
    ";\n";

fs.writeFileSync(outPath, body);

const sizes = Object.values(sources).map((s) => s.length);
console.log(
    "Wrote " +
        path.relative(root, outPath) +
        " (" +
        (Buffer.byteLength(body, "utf8") / 1024).toFixed(1) +
        " KB, " +
        sources.default.length +
        " chars default pattern)"
);

export { sources, outPath };
