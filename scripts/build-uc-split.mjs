/**
 * Splits dev/gdpr.dev.js into uc-boot (sync entry) + uc-core (async).
 * Run: node scripts/build-uc-split.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { spawnSync } from "child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const srcPath = path.join(root, "dev", "gdpr.dev.js");
const bootPath = path.join(root, "dev", "uc-boot.dev.js");
const corePath = path.join(root, "dev", "uc-core.dev.js");
const patternsPath = path.join(root, "dev", "uc-not-required-patterns.dev.js");
const patternsScript = path.join(__dirname, "build-not-required-patterns.mjs");

const patternsResult = spawnSync(process.execPath, [patternsScript], {
    cwd: root,
    encoding: "utf8",
});
if (patternsResult.status !== 0) {
    console.error(patternsResult.stderr || patternsResult.stdout);
    throw new Error("build-not-required-patterns.mjs failed");
}
if (patternsResult.stdout) {
    console.log(patternsResult.stdout.trim());
}

const patternSources = fs.readFileSync(patternsPath, "utf8").trim();

const lines = fs.readFileSync(srcPath, "utf8").split("\n");

/**
 * Minimal sync boot — only code required before the parser hits tracking scripts.
 * Everything else stays in uc-core (async).
 */
const BOOT_RANGES = [
    [1, 7],
    [174, 618], // includes sync script-injection guard (was 174-505; guard inserted after 505, +114 lines)
    [645, 646],
    [1100, 1105],
    [1111, 1134],
    [1149, 1162],
    [1164, 1235],
    [1238, 1333],
    [1348, 1361],
    [1365, 1398],
    [1400, 1471], // includes intaSetGtagConsentDefaults() + oaiq consent intercept — both must fire sync, before uc-core
    [1717, 1735],
    [1742, 1770],
    [2019, 2311], // +49 lines: TCF encoder rewrite (IsRangeEncoding, VLI section, PublisherRestrictions); +1 analytics allowlist entry
    [2381, 2408],
    [4498, 4749],
    [5025, 5334],
];

const CORE_SKIP_LINES = new Set([5463, 5464, 5465]);

function lineDepth(line) {
    let d = 0;
    for (const c of line) {
        if (c === "{") d++;
        if (c === "}") d--;
    }
    return d;
}

function sliceDepth(start, end) {
    let d = 0;
    for (let i = start - 1; i < end; i++) {
        d += lineDepth(lines[i]);
    }
    return d;
}

function takeLines(start, end) {
    return lines.slice(start - 1, end).join("\n");
}

function isBootLine(lineNo) {
    for (const [start, end] of BOOT_RANGES) {
        if (lineNo >= start && lineNo <= end) {
            return true;
        }
    }
    return false;
}

const bootSlices = BOOT_RANGES.map(([start, end]) => takeLines(start, end));

const bootBody = [
    "/*",
    " *  uc-boot — sync CMP guard (loaded as uc.js). Loads uc-core.js async.",
    " *  Generated by scripts/build-uc-split.mjs — edit dev/gdpr.dev.js, then re-run.",
    " */",
    ...bootSlices,
    patternSources,
    `
window.inta_marketingCookieList = window.inta_marketingCookieList || [];
window.inta_functionalCookieList = window.inta_functionalCookieList || [];

function sendToBackend(data) {
    if (typeof window.__intaSendToBackendImpl === "function") {
        return window.__intaSendToBackendImpl(data);
    }
    return Promise.resolve();
}

function recordCookie(value) {
    window.__INTA__COOKIE_EVENTS__ = window.__INTA__COOKIE_EVENTS__ || [];
    window.__INTA__COOKIE_EVENTS__.push(value);
    if (typeof window.__intaRecordCookieImpl === "function") {
        return window.__intaRecordCookieImpl(value);
    }
    window.__intaPendingCookieRecords = window.__intaPendingCookieRecords || [];
    window.__intaPendingCookieRecords.push(value);
}

function intaLoadUcCore() {
    if (window.__intaUcCoreReady || window.__intaUcCoreLoading) {
        return;
    }
    window.__intaUcCoreLoading = true;
    var base = (typeof window.INTA !== "undefined" && window.INTA.settings && window.INTA.settings.coreUrl)
        || "https://consents.cdn.intastellarsolutions.com/uc-core.js";
    if (typeof intastellarDevMode !== "undefined" && intastellarDevMode) {
        base = "../../dev/uc-core.dev.js";
    }
    try {
        var preload = document.createElement("link");
        preload.rel = "preload";
        preload.as = "script";
        preload.href = base;
        preload.crossOrigin = "anonymous";
        (document.head || document.documentElement).appendChild(preload);
    } catch (ePre) { /* ignore */ }
    var s = document.createElement("script");
    s.src = base;
    s.async = true;
    s.onload = function () {
        window.__intaUcCoreReady = true;
        window.__intaUcCoreLoading = false;
        try {
            window.dispatchEvent(new CustomEvent("inta:uc-core-ready"));
        } catch (e) { /* ignore */ }
    };
    s.onerror = function () {
        window.__intaUcCoreLoading = false;
    };
    if (typeof intaAppendToDocumentHead === "function") {
        intaAppendToDocumentHead(s);
    } else {
        (document.head || document.documentElement).appendChild(s);
    }
}

if (!isGtmMode) {
    if (typeof intaBuildNotRequiredRegexp === "function") {
        intaBuildNotRequiredRegexp();
    }
    checkCookieStatus();
}

intaLoadUcCore();
`,
].join("\n");

const coreLines = [
    "/*",
    " *  uc-core — CMP banner, integrations, cookie lists (async from uc.js boot).",
    " *  Generated by scripts/build-uc-split.mjs — edit dev/gdpr.dev.js, then re-run.",
    " *  Top-level bindings are shared with cb.js (same as monolithic gdpr.dev.js).",
    " */",
    "if (window.__intaUcCoreExecuted) {",
    "    console.warn(\"Intastellar uc-core: duplicate load.\");",
    "}",
    "window.__intaUcCoreExecuted = true;",
];

for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1;
    if (isBootLine(lineNo) || CORE_SKIP_LINES.has(lineNo)) {
        continue;
    }
    coreLines.push(lines[i]);
}

coreLines.push(`
if (typeof intaRunUcCoreIntegrations === "function") {
    intaRunUcCoreIntegrations();
}
if (typeof recordCookie === "function") {
    window.__intaRecordCookieImpl = recordCookie;
    var __intaPending = window.__intaPendingCookieRecords;
    if (__intaPending && __intaPending.length) {
        for (var __i = 0; __i < __intaPending.length; __i++) {
            recordCookie(__intaPending[__i]);
        }
        window.__intaPendingCookieRecords = [];
    }
}
if (typeof sendToBackend === "function") {
    window.__intaSendToBackendImpl = sendToBackend;
}
window.__intaUcCoreReady = true;
`);

let bootDepth = 0;
for (const [start, end] of BOOT_RANGES) {
    bootDepth += sliceDepth(start, end);
}

let coreDepth = 0;
for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1;
    if (isBootLine(lineNo) || CORE_SKIP_LINES.has(lineNo)) continue;
    coreDepth += lineDepth(lines[i]);
}

if (bootDepth !== 0 || coreDepth !== 0) {
    console.warn("Warning: brace imbalance boot=" + bootDepth + " core=" + coreDepth);
    if (bootDepth !== 0) {
        throw new Error("uc-boot split has brace imbalance " + bootDepth + " — fix build-uc-split.mjs line ranges");
    }
}

fs.writeFileSync(bootPath, bootBody.trim() + "\n");
fs.writeFileSync(corePath, coreLines.join("\n").trim() + "\n");

const bootKb = (Buffer.byteLength(bootBody, "utf8") / 1024).toFixed(1);
const coreKb = (Buffer.byteLength(coreLines.join("\n"), "utf8") / 1024).toFixed(1);
const bootLines = bootBody.trim().split("\n").length;
console.log("Wrote dev/uc-boot.dev.js (" + bootKb + " KB source, " + bootLines + " lines)");
console.log("Wrote dev/uc-core.dev.js (" + coreKb + " KB source)");
